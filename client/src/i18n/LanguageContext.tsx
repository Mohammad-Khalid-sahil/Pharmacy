export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguage] = useState<Language>(() => (localStorage.getItem('language') as Language) || 'fa');
  const dir: 'rtl' | 'ltr' = language === 'en' ? 'ltr' : 'rtl';

  useEffect(() => {
    localStorage.setItem('language', language);
    document.documentElement.lang = language;
    document.documentElement.dir = dir;
  }, [dir, language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      dir,
      t: (key: keyof typeof dictionaries.en) => pageTranslationOverrides[language][key] || runtimeOverrides[language][key] || (dictionaries[language] as Partial<typeof dictionaries.en>)[key] || dictionaries.en[key]
    }),
    [dir, language]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
};
